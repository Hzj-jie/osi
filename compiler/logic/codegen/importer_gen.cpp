#include <iostream>
#include <sstream>
#include <string>
#include <vector>

static std::string trim(const std::string& s)
{
    const size_t first = s.find_first_not_of(" \t\r\n");
    if (first == std::string::npos) return "";
    const size_t last = s.find_last_not_of(" \t\r\n");
    return s.substr(first, last - first + 1);
}

static std::vector<std::string> split_tabs(const std::string& s)
{
    std::vector<std::string> out;
    std::stringstream ss(s);
    std::string item;
    while (std::getline(ss, item, '\t'))
    {
        if (!item.empty()) out.push_back(item);
    }
    return out;
}

int main()
{
    std::cout << "// This file is generated by importer_gen and definition.txt.\n"
              << "// Do not edit.\n"
              << "#pragma once\n"
              << "#include <cassert>\n"
              << "#include <cstdint>\n"
              << "#include <memory>\n"
              << "#include <string>\n"
              << "#include <vector>\n"
              << "#include \"statements.hpp\"\n"
              << "#include \"../../interpreter/primitive/parser.hpp\"\n"
              << "#include \"../../interpreter/primitive/data_block.hpp\"\n\n"
              << "namespace osi\n"
              << "{\n"
              << "    namespace compiler\n"
              << "    {\n"
              << "        namespace logic\n"
              << "        {\n"
              << "            class importer_definition\n"
              << "            {\n"
              << "            protected:\n"
              << "                static bool parse_typed_parameters(std::vector<parameter>& o, const std::vector<std::string>& v, size_t& p)\n"
              << "                {\n"
              << "                    assert(v.size() > p);\n"
              << "                    if (v[p] != \"(\") return false;\n"
              << "                    p++;\n"
              << "                    while (p < v.size())\n"
              << "                    {\n"
              << "                        if (v[p] == \")\")\n"
              << "                        {\n"
              << "                            p++;\n"
              << "                            return true;\n"
              << "                        }\n"
              << "                        if (p + 1 >= v.size()) return false;\n"
              << "                        std::string param_name = v[p];\n"
              << "                        std::string param_type = v[p + 1];\n"
              << "                        o.emplace_back(param_type, param_name);\n"
              << "                        p += 2;\n"
              << "                    }\n"
              << "                    errors::typed_parameters_is_not_closed();\n"
              << "                    return false;\n"
              << "                }\n\n"
              << "                static bool parse_parameters(std::vector<std::string>& o, const std::vector<std::string>& v, size_t& p)\n"
              << "                {\n"
              << "                    assert(v.size() > p);\n"
              << "                    if (v[p] != \"(\") return false;\n"
              << "                    p++;\n"
              << "                    while (p < v.size())\n"
              << "                    {\n"
              << "                        if (v[p] == \")\")\n"
              << "                        {\n"
              << "                            p++;\n"
              << "                            return true;\n"
              << "                        }\n"
              << "                        o.push_back(v[p]);\n"
              << "                        p++;\n"
              << "                    }\n"
              << "                    errors::parameters_is_not_closed();\n"
              << "                    return false;\n"
              << "                }\n\n"
              << "                bool parse_paragraph(std::shared_ptr<paragraph>& o, const std::vector<std::string>& v, size_t& p)\n"
              << "                {\n"
              << "                    assert(v.size() > p);\n"
              << "                    if (v[p] != \"{\") return false;\n"
              << "                    o = std::make_shared<paragraph>();\n"
              << "                    p++;\n"
              << "                    while (p < v.size())\n"
              << "                    {\n"
              << "                        if (v[p] == \"}\")\n"
              << "                        {\n"
              << "                            p++;\n"
              << "                            return true;\n"
              << "                        }\n"
              << "                        std::shared_ptr<instruction_gen> e;\n"
              << "                        if (!parse(v, p, e)) return false;\n"
              << "                        o->push(std::move(e));\n"
              << "                    }\n"
              << "                    errors::paragraph_is_not_closed();\n"
              << "                    return false;\n"
              << "                }\n\n"
              << "                static bool parse_uint(const std::string& s, uint32_t& o)\n"
              << "                {\n"
              << "                    if (s.empty()) return false;\n"
              << "                    try\n"
              << "                    {\n"
              << "                        size_t idx = 0;\n"
              << "                        unsigned long val = std::stoul(s, &idx);\n"
              << "                        if (idx != s.size()) return false;\n"
              << "                        o = static_cast<uint32_t>(val);\n"
              << "                        return true;\n"
              << "                    }\n"
              << "                    catch (...)\n"
              << "                    {\n"
              << "                        return false;\n"
              << "                    }\n"
              << "                }\n\n";

    std::vector<std::string> keys;
    std::string line;
    while (std::getline(std::cin, line))
    {
        std::string s = trim(line);
        if (s.empty() || s[0] == '#') continue;
        std::vector<std::string> ss = split_tabs(s);
        if (ss.empty()) continue;

        size_t rule_idx = keys.size();
        keys.push_back(ss[0]);

        std::cout << "                bool parse_" << ss[0] << "_" << rule_idx << "(\n"
                  << "                        const std::vector<std::string>& v,\n"
                  << "                        size_t& p,\n"
                  << "                        std::shared_ptr<instruction_gen>& o)\n"
                  << "                {\n"
                  << "                    assert(v.size() > p);\n"
                  << "                    if (v[p] != \"" << ss[0] << "\")\n"
                  << "                    {\n"
                  << "                        return false;\n"
                  << "                    }\n"
                  << "                    size_t start = p;\n"
                  << "                    p += 1;\n";

        for (size_t i = 1; i < ss.size(); ++i)
        {
            std::string pi = "p" + std::to_string(i);
            std::cout << "                    if (p >= v.size())\n"
                      << "                    {\n"
                      << "                        return false;\n"
                      << "                    }\n";
            if (ss[i] == "string")
            {
                std::cout << "                    std::string " << pi << " = v[p];\n";
            }
            else if (ss[i] == "uint")
            {
                std::cout << "                    uint32_t " << pi << " = 0;\n"
                          << "                    if (!parse_uint(v[p], " << pi << "))\n"
                          << "                    {\n"
                          << "                        return false;\n"
                          << "                    }\n";
            }
            else if (ss[i] == "data_block")
            {
                std::cout << "                    primitive::data_block " << pi << ";\n"
                          << "                    if (!primitive::parser::parse_data_block(v[p], " << pi << "))\n"
                          << "                    {\n"
                          << "                        return false;\n"
                          << "                    }\n";
            }
            else if (ss[i] == "parameters")
            {
                std::cout << "                    std::vector<std::string> " << pi << ";\n"
                          << "                    if (!parse_parameters(" << pi << ", v, p))\n"
                          << "                    {\n"
                          << "                        return false;\n"
                          << "                    }\n"
                          << "                    p -= 1;\n";
            }
            else if (ss[i] == "typed_parameters")
            {
                std::cout << "                    std::vector<parameter> " << pi << ";\n"
                          << "                    if (!parse_typed_parameters(" << pi << ", v, p))\n"
                          << "                    {\n"
                          << "                        return false;\n"
                          << "                    }\n"
                          << "                    p -= 1;\n";
            }
            else if (ss[i] == "paragraph")
            {
                std::cout << "                    std::shared_ptr<paragraph> " << pi << ";\n"
                          << "                    if (!parse_paragraph(" << pi << ", v, p))\n"
                          << "                    {\n"
                          << "                        return false;\n"
                          << "                    }\n"
                          << "                    p -= 1;\n";
            }
            else
            {
                std::cout << "                    place_holder " << pi << ";\n"
                          << "                    if (v[p] != \"" << ss[i] << "\")\n"
                          << "                    {\n"
                          << "                        return false;\n"
                          << "                    }\n";
            }
            std::cout << "                    p += 1;\n";
        }

        std::cout << "                    o = std::make_shared<_" << ss[0] << ">(";
        if (ss.size() > 1)
        {
            std::cout << "\n";
            for (size_t i = 1; i < ss.size(); ++i)
            {
                std::cout << "                        p" << i;
                if (i + 1 < ss.size()) std::cout << ",";
                std::cout << "\n";
            }
            std::cout << "                    );\n";
        }
        else
        {
            std::cout << ");\n";
        }
        std::cout << "                    o = instruction_gen_wrapper::maybe_wrap(v, start, p, o);\n"
                  << "                    return true;\n"
                  << "                }\n\n";
    }

    std::cout << "                bool parse(const std::vector<std::string>& v,\n"
              << "                           size_t& p,\n"
              << "                           std::shared_ptr<instruction_gen>& o)\n"
              << "                {\n"
              << "                    if (v.size() <= p)\n"
              << "                    {\n"
              << "                        return false;\n"
              << "                    }\n";
    for (size_t i = 0; i < keys.size(); ++i)
    {
        std::cout << "                    {\n"
                  << "                        size_t pos = p;\n"
                  << "                        if (parse_" << keys[i] << "_" << i << "(v, pos, o))\n"
                  << "                        {\n"
                  << "                            p = pos;\n"
                  << "                            return true;\n"
                  << "                        }\n"
                  << "                    }\n";
    }
    std::cout << "                    errors::unexpected_token(v[p]);\n"
              << "                    return false;\n"
              << "                }\n"
              << "            };\n"
              << "        }\n"
              << "    }\n"
              << "}\n";
    return 0;
}
